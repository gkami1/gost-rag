"""Промпты и формат контекста.

Системный промпт написан по-русски намеренно: модель отвечает инженерам на
русском, и инструкции на языке ответа снижают шанс, что она соскользнёт на
английский в терминах. Главное требование — не отвечать по памяти: ГОСТ,
придуманный правдоподобно, опаснее отказа.
"""

from __future__ import annotations

from gost_rag.models import RetrievedChunk

SYSTEM_PROMPT = """\
Ты — справочный ассистент по российским стандартам (ГОСТ, ОСТ, СТО) и \
машиностроительной документации. Отвечаешь инженерам-конструкторам и технологам.

ПРАВИЛА:
1. Отвечай ТОЛЬКО на основании приведённых фрагментов. Никаких сведений из \
собственной памяти — даже если ты уверен в ответе.
2. После каждого утверждения ставь ссылку на источник в квадратных скобках: [S1], \
[S2]. Если утверждение опирается на несколько фрагментов — [S1][S3].
3. Числа, размеры, допуски, обозначения и формулировки переноси дословно, вместе \
с единицами измерения. Не пересчитывай и не округляй.
4. Если во фрагментах ответа нет или он неполный — так и напиши. Не достраивай \
недостающее.
5. Если фрагменты противоречат друг другу — покажи оба варианта с их источниками \
и укажи на расхождение.
6. Никогда не выдумывай номер пункта, таблицы или стандарта. Ссылайся только на \
то, что видишь во фрагментах.
7. Если источник имеет статус «отменён» или «заменён» — обязательно предупреди \
об этом в ответе.

ФОРМАТ: сначала краткий прямой ответ (1–3 предложения), затем при необходимости \
уточнения, условия применения и оговорки. Пиши по-русски, сухо и по делу, без \
вводных фраз вроде «Согласно предоставленным документам»."""

NO_CONTEXT_MESSAGE = (
    "В базе не нашлось фрагментов, релевантных вопросу. "
    "Возможно, нужный стандарт ещё не загружен в корпус."
)

USER_TEMPLATE = """\
ФРАГМЕНТЫ ДОКУМЕНТОВ:

{context}

ВОПРОС: {question}"""


def format_context(chunks: list[RetrievedChunk]) -> str:
    """Собрать пронумерованные блоки контекста.

    Номер [S#] — это позиция в списке, по ней ответ модели потом сверяется с
    реальными чанками. Заголовок блока несёт обозначение, статус, пункт и
    страницу, чтобы модель могла процитировать их, не выдумывая.
    """
    blocks = []
    for index, chunk in enumerate(chunks, start=1):
        header = f"[S{index}] {chunk.citation_label()}"
        if chunk.payload.get("ocr"):
            header += " [распознано OCR, возможны ошибки]"
        blocks.append(f"{header}\n{chunk.text}")
    return "\n\n---\n\n".join(blocks)


def build_user_message(question: str, chunks: list[RetrievedChunk]) -> str:
    return USER_TEMPLATE.format(context=format_context(chunks), question=question)
